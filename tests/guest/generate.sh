# Regenerates tests/thread_guest.inc from tests/guest/threads.s (needs llvm-mc, llvm-objcopy, llvm-nm).
set -e
cd "$(dirname "$0")"
tmp=$(mktemp -d)
llvm-mc -triple=armv7-none-linux-gnueabi -mcpu=cortex-a9 -filetype=obj threads.s -o "$tmp/t.o"
llvm-objcopy -O binary -j .text "$tmp/t.o" "$tmp/t.bin"
{
  echo "// SPDX-License-Identifier: GPL-2.0-or-later"
  echo "// Generated by tests/guest/generate.sh from tests/guest/threads.s. Do not edit."
  echo "constexpr std::uint32_t guest_words[] = {"
  od -An -v -t x4 -w16 "$tmp/t.bin" | sed 's/\([0-9a-f]\{8\}\)/0x\1,/g; s/^ */    /'
  echo "};"
  llvm-nm "$tmp/t.o" | awk '$2 == "T" || $2 == "t" { if ($3 ~ /^(t_|w_)/) printf "constexpr std::uint32_t sym_%s = 0x%s;\n", $3, $1 }'
} > thread_guest.inc.new
mv thread_guest.inc.new ../thread_guest.inc
rm -rf "$tmp"
