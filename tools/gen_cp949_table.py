"""Regenerates src/cp949_table.inc from Python's cp949 codec (public Unicode mapping data)."""
import sys

LEAD = range(0x81, 0xFF)
TRAIL = range(0x41, 0xFF)

rows = []
count = 0
for lead in LEAD:
    row = []
    for trail in TRAIL:
        try:
            ch = bytes([lead, trail]).decode("cp949")
            cp = ord(ch) if len(ch) == 1 and ord(ch) < 0x10000 else 0
        except UnicodeDecodeError:
            cp = 0
        count += cp != 0
        row.append(cp)
    rows.append(row)

out = ["// SPDX-License-Identifier: GPL-2.0-or-later",
       "// Generated by tools/gen_cp949_table.py; do not edit.",
       "// Rows: lead byte 0x81..0xFE; columns: trail byte 0x41..0xFE; 0 = unmapped.",
       f"// Mapped double-byte entries: {count}"]
for lead, row in zip(LEAD, rows):
    out.append("{" + ",".join(f"0x{v:04X}" if v else "0" for v in row) + "},")
path = sys.argv[1] if len(sys.argv) > 1 else "src/cp949_table.inc"
open(path, "w").write("\n".join(out) + "\n")
print(count)
